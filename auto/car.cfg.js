// Надстройки модели auto/car.glb.
//
// Соглашение: конфиг лежит рядом с моделью и повторяет её имя:
//   auto/car.glb  →  auto/car.cfg.js
// Другая модель подключается адресом: index.html?model=auto/other.glb
// (конфиг подхватится сам: auto/other.cfg.js). Явный путь: ?model=...&cfg=...
//
// Формат — обычный классический скрипт, который кладёт объект в window.CAR_MODEL
// (именно присвоением, а не const — иначе будет конфликт имён с кодом игры).
// Все patterns — строки для new RegExp(pattern, "i"), БЕЗ // и флагов.
// Любое поле можно опустить — тогда берётся встроенный default из index.html.

window.CAR_MODEL = {
  name: 'Стандарт',

  // Размер .glb в байтах — для шкалы прогресса загрузки.
  fileBytes: 27597404,

  // Колёса: узел с началом в центре колеса (ось вращения).
  // Паттерн НЕ должен цеплять узел руля (здесь: steeringwheel).
  wheels: {
    node: '^wheel',
    minR: 0.2,            // узел с диском меньше — не колесо, м
  },

  // Руль в салоне: пустой узел-пивот в ступице + отдельная геометрия.
  steering: {
    pivot: 'steeringwheel', // узел без мешей, стоит в ступице с наклоном колонки
    mesh: 'steeringwheel',  // геометрия руля (имя её родителя)
    axis: 'Y',              // локальная ось пивота = ось вала (X/Y/Z)
    turns: 1.5,             // оборотов руля на полный выворот колёс
  },

  // Поворотники: меши фонарей.
  indicators: {
    pattern: 'indicator',
    // Сторону берём по положению относительно кузова (X), а не из имени:
    // в этой модели передняя пара названа наоборот (lf стоит справа).
    sideByPosition: true,
    xEps: 0.05,             // ближе к оси — неоднозначно, откат на имя, м
  },

  // Номера: пластина с текстурой + отдельные чёрные меши цифр.
  plates: {
    pattern: 'plaka',       // материал таблички
    digits: '^siyah',       // материал мешей-цифр
    text: 'КОЛЕСО',         // надпись вместо цифр
    color: '#12b312',       // её цвет
    flipY: true,            // UV перевёрнуты по вертикали — надпись без переворота встаёт вверх ногами
  },

  // Что считать стёклами (гасятся в салоне), двигателем (прячется в X-ray),
  // дверьми (единственное железо, видимое в зеркалах).
  glass: 'windscreen|window|glass',
  engine: 'engine|block|motor|intake|exhaust_manifold',
  doors: 'door_',

  // Что НЕ входит в замеры габаритов (колёса, зеркала и мелочь).
  excludeWidth: 'wheel|mirror|slipstream|exhaust',
  excludeBody: 'wheel|mirror|slipstream|exhaust|steering',

  // Точка обзора в салоне: поперечно — по рулю, высота — верх руля + сдвиг
  // (но не выше остекления), глубина — середина руля + сдвиг вперёд.
  eye: {
    aboveWheel: 0.19,       // глаза выше верха руля, м
    belowGlass: 0.1,        // глаза ниже верха остекления, м
    forwardOfWheel: 0.5,    // глаза впереди середины руля, м
    driverSideK: 0.3,       // без руля: водитель на 30% ширины слева
  },

  // Физика под модель (необязательно — иначе defaults из CAR).
  physics: {
    maxSpeedKmh: 10,
    accel: 2,
    reverseAccel: 2,
    brake: 18,
    turnDiameter: 10.5,     // диаметр разворота по внешней кромке, м
  },
};
